from app.models import Equipment, EquipmentStatus, ResourceKind, SafetyPrerequisite, Specification

_SYN = "Synthetic catalog record. Not a live university asset or availability listing."


def _spec(name: str, value: str, unit: str | None = None) -> Specification:
    return Specification(name=name, value=value, unit=unit)


def _safety(code: str, description: str) -> SafetyPrerequisite:
    return SafetyPrerequisite(code=code, description=description)


def _eq(
    item_id: str,
    name: str,
    category: str,
    lab_id: str,
    department_id: str,
    detail: str,
    specs: list[Specification],
    safety: list[SafetyPrerequisite],
    status: EquipmentStatus = EquipmentStatus.AVAILABLE,
    kind: ResourceKind = ResourceKind.EQUIPMENT,
) -> Equipment:
    return Equipment(
        id=item_id,
        name=name,
        category=category,
        lab_id=lab_id,
        department_id=department_id,
        description=f"{_SYN} {detail}",
        specifications=specs,
        status=status,
        safety_prerequisites=safety,
        kind=kind,
    )


